"""Boundaries: implementations can change without changing their consumers."""

from collections.abc import Callable, Mapping
from typing import Protocol
from contracts.models import (
    GameDetails,
    GameSummary,
    InstallationResult,
    LibraryFilter,
    OperationStatus,
    Phase,
    PlatformInfo,
)

ProgressCallback = Callable[[Phase], None]


class Backend(Protocol):
    def initialize(self) -> None: ...
    def list_games(
        self, collection: LibraryFilter = LibraryFilter.ALL, term: str = ""
    ) -> tuple[GameSummary, ...]: ...
    def game_details(self, game_id: str) -> GameDetails: ...
    def platform(self, platform_id: str) -> PlatformInfo: ...
    def toggle_favorite(self, game_id: str) -> None: ...
    def install_game(
        self,
        game_id: str,
        version_id: str | None = None,
        on_progress: ProgressCallback | None = None,
    ) -> InstallationResult: ...
    def uninstall_game(self, game_id: str, on_progress: ProgressCallback | None = None) -> None: ...
    def launch_game(self, game_id: str) -> None: ...
    def install_emulator(
        self, emulator_id: str, on_progress: ProgressCallback | None = None
    ) -> str: ...
    def scores(self) -> dict[str, str]: ...


class Actions(Protocol):
    """View events carry identifiers, never widgets or database records."""

    def navigate(self, page: str) -> None: ...
    def open_game(self, game_id: str) -> None: ...
    def search(self, term: str) -> None: ...
    def play(self, game_id: str) -> None: ...
    def install(self, game_id: str, version_id: str | None = None) -> None: ...
    def uninstall(self, game_id: str) -> None: ...
    def toggle_favorite(self, game_id: str) -> None: ...
    def install_emulator(self, emulator_id: str) -> None: ...
    def close(self) -> None: ...


class View(Protocol):
    """Presentation operations called on the main thread by the controller."""

    def show_loading(self) -> None: ...
    def show_catalog(self, page: str, games: tuple[GameSummary, ...]) -> None: ...
    def show_search(self) -> None: ...
    def show_search_results(self, games: tuple[GameSummary, ...]) -> None: ...
    def show_game(self, details: GameDetails) -> None: ...
    def show_platform(self, platform: PlatformInfo) -> None: ...
    def show_settings(self) -> None: ...
    def show_placeholder(self, page: str) -> None: ...
    def show_error(self, message: str) -> None: ...
    def set_operation(self, status: OperationStatus) -> None: ...
    def set_scores(self, scores: Mapping[str, str]) -> None: ...
